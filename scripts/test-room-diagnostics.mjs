import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
const root=path.resolve(import.meta.dirname,"..");
const data=JSON.parse(fs.readFileSync(path.join(root,"site/room-previews/manifest.json"),"utf8"));
const source=JSON.parse(fs.readFileSync(path.join(root,"catalog/room-alias-candidates.json"),"utf8"));
const gallery=JSON.parse(fs.readFileSync(path.join(root,"catalog/showcase.json"),"utf8"));
assert.equal(data.schema_version,1);
assert.equal(data.scenes.length,4);
assert.equal(data.review_only,true);
assert.equal(data.geometry_reconstructed,false);
assert.equal(data.asset_bindings_reconstructed,false);
assert.equal(data.artistic_approval,false);
let positions=0,inherited=0;
for(const entry of data.scenes){
 const original=source.scenes.find(item=>item.id===entry.id);
 assert.ok(original);
 const bytes=fs.readFileSync(path.join(root,entry.source_path));
 const sha=crypto.createHash("sha1").update(Buffer.from("blob "+bytes.length+"\0")).update(bytes).digest("hex");
 assert.equal(sha,entry.source_blob);
 assert.equal(sha,original.blob_sha);
 assert.equal(entry.instances,original.instance_references);
 assert.equal(entry.unresolved_alias_placements,entry.instances);
 assert.equal(entry.explicit_anchors+entry.inherited_positions,entry.instances);
 assert.ok(entry.zones>0);
 assert.ok(!gallery.approved_ids.includes(entry.id));
 assert.match(entry.svg,/^site\/room-previews\/[a-z0-9.-]+\.svg$/);
 const drawing=fs.readFileSync(path.join(root,entry.svg),"utf8");
 assert.ok(drawing.startsWith("<svg"));
 assert.equal((drawing.match(/data-instance="/g)||[]).length,entry.explicit_anchors);
 assert.equal((drawing.match(/data-parented="/g)||[]).length,entry.inherited_positions);
 assert.equal((drawing.match(/data-zone="/g)||[]).length,entry.zones);
 assert.ok(!/<(?:script|image|foreignObject)\b|href=|https?:\/\//i.test(drawing.replace('xmlns="http://www.w3.org/2000/svg"',"")));
 assert.ok(drawing.includes("not model footprints"));
 positions+=entry.explicit_anchors; inherited+=entry.inherited_positions;
}
assert.equal(positions+inherited,37);
console.log("Sceneology room diagnostics passed: 4 real source spatial diagrams; "+positions+" explicit coordinates, "+inherited+" parent-relative positions; 0 new gallery works.");
