import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import {analyzeProxyGeometry} from "../site/room-geometry-audit.mjs";
const root=path.resolve(import.meta.dirname,"..");
const get=p=>JSON.parse(fs.readFileSync(path.join(root,p),"utf8"));
const info=get("site/reading-lumbar-placement-data.json");
const reading=get("site/reading-corner-study-data.json");
const orbit=get("site/family-orbit-data.json");
const showcase=get("catalog/showcase.json");
assert.equal(info.schema_version,1);
assert.equal(info.approved_original_room_placement_recovered,false);
assert.equal(info.proposal_accepted,false);
assert.equal(info.artistically_approved,false);
assert.equal(info.source_pillow_modified,false);
assert.equal(info.source_room_modified,false);
assert.equal(info.gallery_approved,false);
assert.equal(info.candidate_support.scene_identity_inferred,false);
assert.equal(info.candidate_support.mesh_collision_certified,false);
assert.equal(info.candidate_support.chair_touching_other_objects_unverified,true);
assert.equal(showcase.approved_ids.length,24);
assert.equal(info.instance.id,"lumbar-pillow");
assert.equal(reading.omitted_parented_instances.length,2);
const bytes=fs.readFileSync(path.join(root,info.historical_source_scene));
const sha=crypto.createHash("sha1").update(Buffer.from("blob "+bytes.length+"\0")).update(bytes).digest("hex");
assert.equal(sha,info.historical_scene_sha);
const support=info.candidate_support;
assert.equal(support.proposed_rx_deg,-90);
assert.equal(support.candidate_center_panel_faces_outward,true);
assert.equal(support.source_chair_seat_top_y,.66);
assert.equal(support.candidate_pillow_bottom_y,.66);
assert.equal(support.source_chair_back_front_z,.16);
assert.equal(support.candidate_pillow_back_z,.16);
assert.equal(support.horizontal_pillow_overhang_each_side,.2);
assert.equal(support.width_mismatch_requires_owner_review,true);
assert.ok(info.model.faces.length>=8&&info.model.faces.every(face=>face.vertices.length===4&&face.vertices.every(v=>v.length===3&&v.every(Number.isFinite))));
const originalModel=orbit.models.find(m=>m.key==="lumbar-pillow");
assert.equal(originalModel.source_sha,info.source_pillow_sha);
const localOrigin=p=>p;
const transformed=originalModel.faces[0].vertices[0];
const expected=[transformed[0],transformed[2]+.87,-transformed[1]+.16].map(x=>Number(x.toFixed(6)));
assert.deepEqual(info.model.faces[0].vertices[0],expected);
const models=new Map([...orbit.models.map(m=>[m.key,m]),[info.model.key,info.model]]);
const diagnostics=analyzeProxyGeometry([...reading.instances,info.instance],models);
assert.equal(diagnostics.instances.length,7);
assert.equal(diagnostics.source_model_bindings_certified,false);
assert.ok(diagnostics.instances.some(i=>i.id==="lumbar-pillow"));
console.log("Sceneology lumbar proposal QA: original room and source pillow immutable; seat contact, backrest plane, accent direction and 0.2 unit overhang tested. No acceptance.");
